"""The personal-scale ResearchGraph corpus: a canonical corpus plus a conversation history.

A graph benchmark needs a shape the *graph* is personal-scale at, which is not the same
shape as the corpus benchmark of Task 17.3. That one sizes the canonical write path and
the projection rebuild at 1,000 works; the graph's budgets are about how long a lookup and
a two-hop walk take once the index exists, and those scale with nodes and adjacency rather
than with how many evidence records were parsed. The agreed shape at ``--scale 1.0`` is:

===================================== =========
namespace                              count
===================================== =========
Works / Versions / Artifacts           200 each
document blocks                        20,000
accepted Evidence                      10,000
Claims (3 evidence relations each)     1,000
manuscript anchors                     100
conversation sessions                  40
messages                               1,200
session attachments                    200
===================================== =========

That is a researcher two or three years into a project: a few hundred read papers, a
thousand claims, and a chat history to match. It projects roughly 32,000 nodes and 100,000
edges, which is the size the §9 budgets are quoted at.

The canonical half is generated by :func:`benchmarks.generate_corpus.generate_workspace`
at the fraction that yields those counts, so the two benchmarks measure the *same* corpus
generator and cannot drift. The conversation half is written through `ConversationStore`,
so every durable file a session projects from is a real one.

Determinism: a seed fixes the text, the ids, and the structure. Session timestamps come
from the wall clock (`ConversationStore` stamps them), so two runs differ in those fields
and in nothing else that the graph indexes.

    uv run python -m benchmarks.graph.generate_graph_corpus --root /tmp/graph --scale 1.0
"""

