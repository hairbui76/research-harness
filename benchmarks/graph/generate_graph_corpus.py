from dataclasses import asdict, dataclass
from functools import partial
from pathlib import Path
from typing import Any

from benchmarks.generate_corpus import WORKS as CORPUS_WORKS
from benchmarks.generate_corpus import GenerationReport, generate_workspace
from research_harness.domain.base import Provenance
from research_harness.domain.conversation import (
    AttachmentBlock,
    AttachmentState,
    Message,
    MessageRole,
    ReferenceBlock,
    SessionAttachment,
    SessionDefaults,
    TextBlock,
    Visibility,
)
from research_harness.domain.ids import (
    ClaimId,
    ConversationSessionId,
    EvidenceId,
    MessageId,
    SessionAttachmentId,
    WorkId,
)
from research_harness.workspace.conversations import ConversationStore
from research_harness.workspace.repository import WorkspaceRepository

__all__ = [
    "ATTACHMENTS_PER_SESSION",
    "GRAPH_CORPUS_WORKS",
    "MESSAGES_PER_SESSION",
    "PRIVATE_SESSION_EVERY",
    "SESSIONS",
    "GraphCorpusReport",
    "generate_graph_workspace",
    "main",
]

logger = logging.getLogger(__name__)

GRAPH_CORPUS_WORKS = 200
"""Works at ``--scale 1.0``; the canonical generator is called at the matching fraction."""

SESSIONS = 40
MESSAGES_PER_SESSION = 30
ATTACHMENTS_PER_SESSION = 5
PRIVATE_SESSION_EVERY = 3
"""Every third session is `private`, so the privacy-filtered traversal has work to do."""

REFERENCES_PER_SESSION = 6
"""Messages carrying an `@` reference, which is what makes `mentioned_in` edges exist."""

ACTOR = "human:benchmark"

_ATTACHMENT_BYTES = b"%PDF-1.7\n% synthetic session attachment\n"
_QUESTIONS: tuple[str, ...] = (
    "What does the evidence say about {topic}?",
    "Summarize the disagreement over {topic}.",
    "Which works report {topic} on a held-out split?",
    "Is the {topic} result reproducible from the stored parse?",
    "Draft a paragraph about {topic} with the anchors attached.",
)
_ANSWERS: tuple[str, ...] = (
    "The accepted evidence on {topic} is mixed; two works report it directly and one "
    "contradicts the reported figure.",
    "Nothing accepted covers {topic} yet. The nearest support is a table cell whose "
    "anchor is still fresh.",
    "{topic} is supported at the individual-work level only; the field-level statement "
    "would need a decision.",
)
_TOPICS: tuple[str, ...] = (
    "CICIDS2017",
    "UNSW-NB15",
    "ImageNet",
    "LibriSpeech",
    "MIMIC-III",
    "calibration error",
    "distribution shift",
    "inference latency",
    "tokenization granularity",
    "held-out splits",
)


@dataclass(frozen=True, slots=True)
class GraphCorpusReport:
    """What one graph-corpus generation produced."""

    root: str
    seed: int
    scale: float
    canonical: dict[str, Any]
    sessions: int
    messages: int
    attachments: int
    private_sessions: int
    references: int
    duration_s: float

    def as_dict(self) -> dict[str, Any]:
        """JSON-ready form."""
        return asdict(self)

    def summary(self) -> str:
        """One line for a terminal or a log."""
        return (
            f"{self.canonical['works']} works, {self.canonical['blocks']} blocks, "
            f"{self.canonical['evidence']} evidence, {self.canonical['claims']} claims, "
            f"{self.sessions} sessions ({self.private_sessions} private), "
            f"{self.messages} messages, {self.attachments} attachments "
            f"in {self.duration_s:.1f}s"
        )


def corpus_scale(scale: float) -> float:
    """The `benchmarks.generate_corpus` scale that yields this benchmark's work count."""
    return scale * GRAPH_CORPUS_WORKS / CORPUS_WORKS


def generate_graph_workspace(
    root: Path,
    *,
    scale: float = 1.0,
    seed: int = 7,
    sessions: int = SESSIONS,
    messages_per_session: int = MESSAGES_PER_SESSION,
    attachments_per_session: int = ATTACHMENTS_PER_SESSION,
) -> GraphCorpusReport:
    """Build the personal-scale graph corpus at ``root`` and report what it contains."""
    started = time.perf_counter()
    target = Path(root)
    canonical = generate_workspace(target, scale=corpus_scale(scale), seed=seed)
    repo = WorkspaceRepository.open(target, repair=True)
    written = _generate_conversations(
        repo,
        canonical,
        seed=seed,
        sessions=max(1, round(sessions * scale)),
        messages_per_session=messages_per_session,
        attachments_per_session=attachments_per_session,
    )
    return GraphCorpusReport(
        root=str(target),
        seed=seed,
        scale=scale,
        canonical=canonical.as_dict(),
        duration_s=time.perf_counter() - started,
        **written,
    )


def _generate_conversations(
    repo: WorkspaceRepository,
    canonical: GenerationReport,
    *,
    seed: int,
    sessions: int,
    messages_per_session: int,
    attachments_per_session: int,
) -> dict[str, int]:
    """Sessions, transcripts, and attachments over the canonical corpus just generated."""
    store = ConversationStore.for_repository(repo)
    rng = random.Random(seed)
    provenance = Provenance.human(ACTOR)
    targets = _reference_targets(canonical)
    counts = {
        "sessions": 0,
        "messages": 0,
        "attachments": 0,
        "private_sessions": 0,
        "references": 0,
    }
    for index in range(sessions):
        private = index % PRIVATE_SESSION_EVERY == 0
        topic = _TOPICS[index % len(_TOPICS)]
        session = store.create_session(
            title=f"{'Private' if private else 'Shared'} notes on {topic}",
            provenance=provenance,
            visibility=Visibility.PRIVATE if private else Visibility.PROJECT,
            defaults=SessionDefaults(mode="research", token_budget=8_000),
        )
        counts["sessions"] += 1
        counts["private_sessions"] += int(private)
        attachments = [
            _attach(store, session.id, provenance, private=private, index=item)
            for item in range(attachments_per_session)
        ]
        counts["attachments"] += len(attachments)
        counts["references"] += _write_transcript(
            store,
            session.id,
            provenance,
            rng=rng,
            private=private,
            topic=topic,
            count=messages_per_session,
            targets=targets,
            attachments=attachments,
        )
        counts["messages"] += messages_per_session
    return counts


def _reference_targets(canonical: GenerationReport) -> tuple[str, ...]:
    """Stable ids the transcript points at: works, claims, and accepted evidence."""
    works = [str(WorkId(f"W{index:04d}")) for index in range(1, canonical.works + 1)]
    claims = [str(ClaimId(f"C{index:04d}")) for index in range(1, canonical.claims + 1)]
    evidence = [str(EvidenceId(f"E{index:04d}")) for index in range(1, canonical.evidence + 1)]
    return tuple(works[:200] + claims[:200] + evidence[:200])


def _attach(
    store: ConversationStore,
    session: ConversationSessionId,
    provenance: Provenance,
    *,
    private: bool,
    index: int,
) -> SessionAttachmentId:
    """One ready session attachment with its bytes stored, exactly as an intake writes it."""
    data = _ATTACHMENT_BYTES + f"{session}-{index}\n".encode()
    build = partial(
        _attachment,
        session=session,
        data=data,
        index=index,
        private=private,
        provenance=provenance,
    )
    return store.add_attachment(session, build, data=data).id


def _attachment(
    new_id: SessionAttachmentId,
    *,
    session: ConversationSessionId,
    data: bytes,
    index: int,
    private: bool,
    provenance: Provenance,
) -> SessionAttachment:
    """The record `add_attachment` writes once it has allocated an `SA####`."""
    return SessionAttachment(
        id=new_id,
        session=session,
        state=AttachmentState.READY,
        filename=f"note-{index}.pdf",
        media_type="application/pdf",
        size_bytes=len(data),
        content_hash=f"sha256:{hashlib.sha256(data).hexdigest()}",
        page_count=1,
        description=f"attachment {index} of {session}",
        visibility=Visibility.PRIVATE if private else Visibility.PROJECT,
        provenance=provenance,
    )


def _write_transcript(
    store: ConversationStore,
    session: ConversationSessionId,
    provenance: Provenance,
    *,
    rng: random.Random,
    private: bool,
    topic: str,
    count: int,
    targets: Sequence[str],
    attachments: Sequence[SessionAttachmentId],
) -> int:
    """Alternating user/assistant turns; every few turns carries a reference or a file."""
    visibility = Visibility.PRIVATE if private else Visibility.PROJECT
    references = 0
    for index in range(count):
        user = index % 2 == 0
        text = (
            _QUESTIONS[index // 2 % len(_QUESTIONS)]
            if user
            else _ANSWERS[index // 2 % len(_ANSWERS)]
        ).format(topic=topic)
        blocks: list[Any] = [TextBlock(text=text)]
        carried: list[SessionAttachmentId] = []
        if user and index % (2 * max(1, count // REFERENCES_PER_SESSION)) == 0 and targets:
            blocks.append(_reference(rng.choice(list(targets))))
            references += 1
        if user and attachments and index // 2 < len(attachments):
            carried = [attachments[index // 2]]
            blocks.append(AttachmentBlock(attachment=carried[0], caption=f"{topic} figure"))
        store.append_message(
            session,
            partial(
                _message,
                session=session,
                role=MessageRole.USER if user else MessageRole.ASSISTANT,
                blocks=tuple(blocks),
                visibility=visibility,
                attachments=tuple(carried),
                provenance=provenance,
            ),
        )
    return references


def _message(
    new_id: MessageId,
    *,
    session: ConversationSessionId,
    role: MessageRole,
    blocks: tuple[Any, ...],
    visibility: Visibility,
    attachments: tuple[SessionAttachmentId, ...],
    provenance: Provenance,
) -> Message:
    """The transcript line `append_message` writes once it has allocated an `M####`."""
    return Message(
        id=new_id,
        session=session,
        role=role,
        blocks=blocks,
        visibility=visibility,
        attachments=attachments,
        provenance=provenance,
    )


def _reference(target: str) -> ReferenceBlock:
    """A composer reference block for a stable id."""
    if target.startswith("W"):
        return ReferenceBlock(target=WorkId(target), label=target)
    if target.startswith("C"):
        return ReferenceBlock(target=ClaimId(target), label=target)
    return ReferenceBlock(target=EvidenceId(target), label=target)


def main(argv: Sequence[str] | None = None) -> int:
    """CLI: build the graph benchmark corpus and print its report as JSON."""
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--root", type=Path, required=True, help="directory to create")
    parser.add_argument("--scale", type=float, default=1.0, help="fraction of the agreed shape")
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--sessions", type=int, default=SESSIONS)
    parser.add_argument("--messages-per-session", type=int, default=MESSAGES_PER_SESSION)
    parser.add_argument("--attachments-per-session", type=int, default=ATTACHMENTS_PER_SESSION)
    parser.add_argument("--verbose", action="store_true")
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO if args.verbose else logging.WARNING)
    report = generate_graph_workspace(
        args.root,
        scale=args.scale,
        seed=args.seed,
        sessions=args.sessions,
        messages_per_session=args.messages_per_session,
        attachments_per_session=args.attachments_per_session,
    )
    print(json.dumps(report.as_dict(), indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":  # pragma: no cover - module entry point
    sys.exit(main())
